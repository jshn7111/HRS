-- StayEase / AI Hotel Booking Platform - Complete Supabase Setup
-- Run this file in Supabase Dashboard -> SQL Editor -> New query.
--
-- What this sets up:
-- 1. Auth profile table linked to auth.users
-- 2. Auto profile creation on user signup
-- 3. Hotels table compatible with both:
--    - requested dataset fields: hotel_name, address, latitude, longitude, price_per_night, image_url
--    - existing app fields: name, slug, location, price_from, images
-- 4. Rooms, bookings, reviews, wishlist, contact messages
-- 5. Indexes, triggers, RLS policies, and role helpers
--
-- Important:
-- Supabase Auth itself is built into every Supabase project. SQL can create
-- profile triggers and database policies, but email provider / OTP / redirect
-- URL settings must be configured from the Supabase Dashboard.

BEGIN;

-- ============================================================
-- EXTENSIONS
-- ============================================================
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================
-- HELPERS
-- ============================================================
CREATE OR REPLACE FUNCTION public.slugify(value TEXT)
RETURNS TEXT AS $$
  SELECT trim(BOTH '-' FROM regexp_replace(lower(coalesce(value, '')), '[^a-z0-9]+', '-', 'g'));
$$ LANGUAGE sql IMMUTABLE;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================================
-- PROFILES - EXTENDS SUPABASE AUTH USERS
-- ============================================================
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  email TEXT UNIQUE,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'owner', 'admin')),
  avatar_url TEXT,
  phone TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_profiles_role ON public.profiles(role);
CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
  requested_role TEXT;
BEGIN
  requested_role := COALESCE(NEW.raw_user_meta_data->>'role', 'user');

  INSERT INTO public.profiles (id, name, email, role)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(NEW.raw_user_meta_data->>'name', ''), split_part(NEW.email, '@', 1), 'User'),
    NEW.email,
    CASE
      WHEN requested_role = 'owner' THEN 'owner'
      ELSE 'user'
    END
  )
  ON CONFLICT (id) DO UPDATE SET
    name = EXCLUDED.name,
    email = EXCLUDED.email,
    updated_at = NOW();

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

DROP TRIGGER IF EXISTS profiles_updated_at ON public.profiles;
CREATE TRIGGER profiles_updated_at
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE OR REPLACE FUNCTION public.current_user_role()
RETURNS TEXT AS $$
  SELECT role FROM public.profiles WHERE id = auth.uid();
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
  SELECT COALESCE(public.current_user_role() = 'admin', false);
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;

-- ============================================================
-- HOTELS
-- ============================================================
CREATE TABLE IF NOT EXISTS public.hotels (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100001) PRIMARY KEY,
  owner_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,

  -- Requested structure
  hotel_name TEXT,
  city TEXT NOT NULL,
  state TEXT,
  address TEXT,
  latitude NUMERIC(9,6) CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  longitude NUMERIC(9,6) CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
  star_rating NUMERIC(2,1) CHECK (star_rating IS NULL OR star_rating BETWEEN 1 AND 5),
  review_score NUMERIC(2,1) DEFAULT 0 CHECK (review_score BETWEEN 0 AND 5),
  review_count INTEGER DEFAULT 0 CHECK (review_count >= 0),
  price_per_night INTEGER DEFAULT 0 CHECK (price_per_night >= 0),
  category TEXT CHECK (category IS NULL OR category IN ('Budget', 'Standard', 'Premium', 'Luxury')),
  amenities TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  description TEXT,
  image_url TEXT,
  phone TEXT,
  email TEXT,

  -- Existing React app compatibility fields
  name TEXT,
  slug TEXT UNIQUE,
  location TEXT,
  country TEXT NOT NULL DEFAULT 'India',
  images TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  rating NUMERIC(3,2) DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
  price_from INTEGER DEFAULT 0 CHECK (price_from >= 0),
  is_verified BOOLEAN NOT NULL DEFAULT false,
  is_featured BOOLEAN NOT NULL DEFAULT false,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CONSTRAINT hotels_has_name CHECK (hotel_name IS NOT NULL OR name IS NOT NULL),
  CONSTRAINT hotels_has_location CHECK (address IS NOT NULL OR location IS NOT NULL)
);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'hotels_hotel_name_key'
      AND conrelid = 'public.hotels'::regclass
  ) THEN
    ALTER TABLE public.hotels
      ADD CONSTRAINT hotels_hotel_name_key UNIQUE (hotel_name);
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.set_hotel_defaults()
RETURNS TRIGGER AS $$
BEGIN
  NEW.hotel_name := COALESCE(NULLIF(NEW.hotel_name, ''), NULLIF(NEW.name, ''));
  NEW.name := COALESCE(NULLIF(NEW.name, ''), NEW.hotel_name);

  NEW.address := COALESCE(NULLIF(NEW.address, ''), NULLIF(NEW.location, ''));
  NEW.location := COALESCE(NULLIF(NEW.location, ''), NEW.address);

  NEW.price_per_night := COALESCE(NULLIF(NEW.price_per_night, 0), NEW.price_from, 0);
  NEW.price_from := COALESCE(NULLIF(NEW.price_from, 0), NEW.price_per_night, 0);

  IF (NEW.image_url IS NULL OR NEW.image_url = '') AND cardinality(NEW.images) > 0 THEN
    NEW.image_url := NEW.images[1];
  END IF;

  IF (NEW.images IS NULL OR cardinality(NEW.images) = 0) AND NEW.image_url IS NOT NULL THEN
    NEW.images := ARRAY[NEW.image_url];
  END IF;

  NEW.rating := COALESCE(NULLIF(NEW.rating, 0), NEW.review_score, 0);

  IF NEW.slug IS NULL OR NEW.slug = '' THEN
    NEW.slug := public.slugify(
      NEW.hotel_name || '-' || COALESCE(NEW.id::TEXT, substr(gen_random_uuid()::TEXT, 1, 8))
    );
  ELSE
    NEW.slug := public.slugify(NEW.slug);
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS hotels_set_defaults ON public.hotels;
CREATE TRIGGER hotels_set_defaults
  BEFORE INSERT OR UPDATE ON public.hotels
  FOR EACH ROW EXECUTE FUNCTION public.set_hotel_defaults();

DROP TRIGGER IF EXISTS hotels_updated_at ON public.hotels;
CREATE TRIGGER hotels_updated_at
  BEFORE UPDATE ON public.hotels
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE INDEX IF NOT EXISTS idx_hotels_city ON public.hotels(city);
CREATE INDEX IF NOT EXISTS idx_hotels_state ON public.hotels(state);
CREATE INDEX IF NOT EXISTS idx_hotels_slug ON public.hotels(slug);
CREATE INDEX IF NOT EXISTS idx_hotels_location ON public.hotels(latitude, longitude);
CREATE INDEX IF NOT EXISTS idx_hotels_price ON public.hotels(price_per_night);
CREATE INDEX IF NOT EXISTS idx_hotels_category ON public.hotels(category);
CREATE INDEX IF NOT EXISTS idx_hotels_featured ON public.hotels(is_featured) WHERE is_featured = true;
CREATE INDEX IF NOT EXISTS idx_hotels_amenities ON public.hotels USING GIN (amenities);

CREATE OR REPLACE FUNCTION public.owns_hotel(target_hotel_id INTEGER)
RETURNS BOOLEAN AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.hotels
    WHERE id = target_hotel_id
      AND owner_id = auth.uid()
  );
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;

